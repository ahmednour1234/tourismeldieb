CREATE INDEX IF NOT EXISTS tour_departures_status_date_index ON tour_departures (status, departure_date);
CREATE INDEX IF NOT EXISTS tour_departures_date_status_index ON tour_departures (departure_date, status);
CREATE INDEX IF NOT EXISTS tour_departures_cutoff_index ON tour_departures (booking_cutoff_at);
CREATE INDEX IF NOT EXISTS tour_blackout_dates_tour_range_index ON tour_blackout_dates (tour_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS tour_blackout_dates_option_range_index ON tour_blackout_dates (tour_option_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS tour_prices_option_guest_currency_index ON tour_prices (tour_option_id, guest_type, currency_id);
CREATE INDEX IF NOT EXISTS tour_prices_valid_active_index ON tour_prices (valid_from, valid_to, is_active);
CREATE UNIQUE INDEX IF NOT EXISTS tour_prices_active_unique_index ON tour_prices (tour_option_id, guest_type, currency_id, (COALESCE(valid_from, DATE '0001-01-01'))) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS pricing_rules_tour_active_index ON pricing_rules (tour_id, is_active);
CREATE INDEX IF NOT EXISTS pricing_rules_option_active_index ON pricing_rules (tour_option_id, is_active);
CREATE INDEX IF NOT EXISTS pricing_rules_period_index ON pricing_rules (starts_at, ends_at);
CREATE INDEX IF NOT EXISTS currency_rates_pair_active_index ON currency_rates (base_currency_id, target_currency_id, is_active);
CREATE INDEX IF NOT EXISTS coupons_active_period_index ON coupons (is_active, starts_at, expires_at);

