-- Phase 2 direct PostgreSQL schema and demo data.
--
-- Run after Laravel's base migrations have created the users table:
--
--   psql -U postgres -d tourismeldieb -f database/sql/phase2_postgresql_schema_seed.sql
--
-- This script mirrors the Phase 2 Laravel migrations and seeders added to the
-- project. It is intentionally PostgreSQL-specific and uses ON CONFLICT for
-- repeatable demo data loading.

BEGIN;

CREATE TABLE IF NOT EXISTS languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    native_name VARCHAR(255) NOT NULL,
    direction VARCHAR(3) NOT NULL DEFAULT 'ltr',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS currencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code CHAR(3) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    symbol VARCHAR(12) NOT NULL,
    decimal_places SMALLINT NOT NULL DEFAULT 2,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS countries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_id BIGINT NULL REFERENCES currencies(id) ON DELETE SET NULL,
    code CHAR(2) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    phone_code VARCHAR(12) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS destinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id BIGINT NULL REFERENCES countries(id) ON DELETE SET NULL,
    code VARCHAR(255) NOT NULL UNIQUE,
    timezone VARCHAR(255) NOT NULL DEFAULT 'Africa/Cairo',
    image_url VARCHAR(1000) NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS destination_translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT NOT NULL REFERENCES destinations(id) ON DELETE CASCADE,
    locale VARCHAR(10) NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    short_description TEXT NULL,
    description TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (destination_id, locale),
    UNIQUE (locale, slug)
);

CREATE TABLE IF NOT EXISTS tour_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NULL REFERENCES tour_categories(id) ON DELETE SET NULL,
    code VARCHAR(255) NOT NULL UNIQUE,
    image_url VARCHAR(1000) NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS tour_category_translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_category_id BIGINT NOT NULL REFERENCES tour_categories(id) ON DELETE CASCADE,
    locale VARCHAR(10) NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    description TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (tour_category_id, locale),
    UNIQUE (locale, slug)
);

CREATE TABLE IF NOT EXISTS tours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT NOT NULL REFERENCES destinations(id) ON DELETE RESTRICT,
    tour_category_id BIGINT NULL REFERENCES tour_categories(id) ON DELETE SET NULL,
    code VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'draft',
    duration_value SMALLINT NULL,
    duration_unit VARCHAR(20) NULL,
    tour_type VARCHAR(20) NOT NULL DEFAULT 'shared',
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_best_seller BOOLEAN NOT NULL DEFAULT FALSE,
    is_last_minute BOOLEAN NOT NULL DEFAULT FALSE,
    minimum_age SMALLINT NULL,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    published_at TIMESTAMP NULL,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS tour_translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    locale VARCHAR(10) NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    short_description TEXT NULL,
    description TEXT NULL,
    highlights JSONB NULL,
    itinerary JSONB NULL,
    included JSONB NULL,
    excluded JSONB NULL,
    faqs JSONB NULL,
    seo_title VARCHAR(255) NULL,
    seo_description TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (tour_id, locale),
    UNIQUE (locale, slug)
);

CREATE TABLE IF NOT EXISTS tour_operating_languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (tour_id, language_id)
);

CREATE TABLE IF NOT EXISTS tour_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE RESTRICT,
    code VARCHAR(255) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    minimum_guests SMALLINT NOT NULL DEFAULT 1 CHECK (minimum_guests >= 1),
    maximum_guests SMALLINT NOT NULL,
    minimum_booking_quantity SMALLINT NOT NULL DEFAULT 1 CHECK (minimum_booking_quantity >= 1),
    maximum_booking_quantity SMALLINT NOT NULL,
    duration_value SMALLINT NULL,
    duration_unit VARCHAR(20) NOT NULL DEFAULT 'hour',
    is_private BOOLEAN NOT NULL DEFAULT FALSE,
    requires_manual_confirmation BOOLEAN NOT NULL DEFAULT FALSE,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    UNIQUE (tour_id, code),
    CHECK (maximum_guests >= minimum_guests),
    CHECK (maximum_booking_quantity <= capacity)
);

CREATE TABLE IF NOT EXISTS tour_option_translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    tour_option_id BIGINT NOT NULL REFERENCES tour_options(id) ON DELETE CASCADE,
    locale VARCHAR(10) NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    short_description TEXT NULL,
    description TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (tour_option_id, locale),
    UNIQUE (tour_id, locale, slug)
);

CREATE TABLE IF NOT EXISTS tour_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_option_id BIGINT NOT NULL REFERENCES tour_options(id) ON DELETE RESTRICT,
    day_of_week VARCHAR(20) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NULL,
    capacity_override INTEGER NULL CHECK (capacity_override IS NULL OR capacity_override > 0),
    pickup_start_time TIME NULL,
    booking_cutoff_hours SMALLINT NOT NULL DEFAULT 24 CHECK (booking_cutoff_hours >= 0),
    booking_opens_days_before SMALLINT NOT NULL DEFAULT 90,
    valid_from DATE NULL,
    valid_to DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS tour_departures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_option_id BIGINT NOT NULL REFERENCES tour_options(id) ON DELETE RESTRICT,
    tour_schedule_id BIGINT NULL REFERENCES tour_schedules(id) ON DELETE SET NULL,
    departure_date DATE NOT NULL,
    start_datetime TIMESTAMP NOT NULL,
    end_datetime TIMESTAMP NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    reserved_capacity INTEGER NOT NULL DEFAULT 0 CHECK (reserved_capacity >= 0),
    confirmed_capacity INTEGER NOT NULL DEFAULT 0 CHECK (confirmed_capacity >= 0),
    available_capacity INTEGER NOT NULL DEFAULT 0 CHECK (available_capacity >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    booking_opens_at TIMESTAMP NULL,
    booking_cutoff_at TIMESTAMP NULL,
    manual_notes TEXT NULL,
    generated_automatically BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    UNIQUE (tour_option_id, start_datetime),
    CHECK (reserved_capacity + confirmed_capacity <= capacity)
);

CREATE TABLE IF NOT EXISTS tour_blackout_dates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE RESTRICT,
    tour_option_id BIGINT NULL REFERENCES tour_options(id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR(255) NULL,
    internal_notes TEXT NULL,
    cancel_existing_departures BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS tour_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_option_id BIGINT NOT NULL REFERENCES tour_options(id) ON DELETE RESTRICT,
    guest_type VARCHAR(30) NOT NULL,
    currency_id BIGINT NOT NULL REFERENCES currencies(id) ON DELETE RESTRICT,
    amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0),
    minimum_quantity SMALLINT NOT NULL DEFAULT 1,
    maximum_quantity SMALLINT NULL,
    valid_from DATE NULL,
    valid_to DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS pricing_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE RESTRICT,
    tour_option_id BIGINT NULL REFERENCES tour_options(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    rule_type VARCHAR(30) NOT NULL,
    adjustment_type VARCHAR(40) NOT NULL,
    adjustment_value INTEGER NOT NULL,
    currency_id BIGINT NULL REFERENCES currencies(id) ON DELETE RESTRICT,
    priority INTEGER NOT NULL DEFAULT 0,
    starts_at TIMESTAMP NULL,
    ends_at TIMESTAMP NULL,
    days_of_week JSONB NULL,
    minimum_guests SMALLINT NULL,
    maximum_guests SMALLINT NULL,
    minimum_days_before SMALLINT NULL,
    maximum_days_before SMALLINT NULL,
    applies_to_guest_type VARCHAR(30) NULL,
    stacking_mode VARCHAR(30) NOT NULL DEFAULT 'stackable',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at),
    CHECK (maximum_guests IS NULL OR minimum_guests IS NULL OR maximum_guests >= minimum_guests),
    CHECK (maximum_days_before IS NULL OR minimum_days_before IS NULL OR maximum_days_before >= minimum_days_before)
);

CREATE TABLE IF NOT EXISTS currency_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_currency_id BIGINT NOT NULL REFERENCES currencies(id) ON DELETE RESTRICT,
    target_currency_id BIGINT NOT NULL REFERENCES currencies(id) ON DELETE RESTRICT,
    rate NUMERIC(20, 10) NOT NULL,
    effective_at TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    UNIQUE (base_currency_id, target_currency_id, effective_at)
);

CREATE TABLE IF NOT EXISTS coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    discount_type VARCHAR(30) NOT NULL,
    discount_value INTEGER NOT NULL,
    currency_id BIGINT NULL REFERENCES currencies(id) ON DELETE RESTRICT,
    maximum_discount_minor BIGINT NULL,
    minimum_order_minor BIGINT NULL,
    usage_limit INTEGER NULL,
    usage_limit_per_customer INTEGER NULL,
    used_count INTEGER NOT NULL DEFAULT 0,
    starts_at TIMESTAMP NULL,
    expires_at TIMESTAMP NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    CHECK (expires_at IS NULL OR starts_at IS NULL OR expires_at >= starts_at)
);

CREATE TABLE IF NOT EXISTS coupon_tour (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    tour_id BIGINT NOT NULL REFERENCES tours(id) ON DELETE CASCADE,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (coupon_id, tour_id)
);

CREATE TABLE IF NOT EXISTS coupon_tour_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    tour_option_id BIGINT NOT NULL REFERENCES tour_options(id) ON DELETE CASCADE,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    UNIQUE (coupon_id, tour_option_id)
);

CREATE INDEX IF NOT EXISTS languages_active_index ON languages (is_active);
