CREATE INDEX IF NOT EXISTS tours_category_status_index ON tours (tour_category_id, status);
CREATE INDEX IF NOT EXISTS tour_options_tour_active_index ON tour_options (tour_id, is_active);
CREATE INDEX IF NOT EXISTS tour_options_tour_default_index ON tour_options (tour_id, is_default);
